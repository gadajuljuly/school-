// Reading fluency norm (words per minute) by grade, from the academic profile.
function fluencyNorm(grade) {
  const g = +grade;
  if (!g) return '';
  if (g <= 2) return '20–40';
  if (g <= 4) return '40–60';
  if (g <= 6) return '60–80';
  return '120';
}

